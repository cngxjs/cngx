import { describe, expect, it } from 'vitest';

import { createProvenanceStamp, hasProvenanceMarker, hasProvenanceStamp, withProvenanceMarker } from './provenance';

const IMPORT_LINE = "@import '@cngx/themes/cngx.css';\n";

describe('createProvenanceStamp', () => {
  it('writes the generated line and the source line', () => {
    const stamp = createProvenanceStamp('ng-add', '0.1.0');
    const [first, second, rest] = stamp.split('\n');

    expect(first).toMatch(/^\/\* cngx:generated [0-9a-f]{8} \*\/$/);
    expect(second).toBe('/* ng-add, @cngx 0.1.0 */');
    expect(rest).toBe('');
  });

  it('is deterministic per source and version', () => {
    expect(createProvenanceStamp('ng-add', '0.1.0')).toBe(createProvenanceStamp('ng-add', '0.1.0'));
    expect(createProvenanceStamp('ng-add', '0.1.0')).not.toBe(createProvenanceStamp('ng-add', '0.2.0'));
  });
});

describe('hasProvenanceStamp', () => {
  it('finds a stamp at the start of a file', () => {
    expect(hasProvenanceStamp(`${createProvenanceStamp('ng-add', '0.1.0')}:root {}\n`)).toBe(true);
  });

  it('ignores a stamp further down and a hand-written look-alike', () => {
    expect(hasProvenanceStamp(`:root {}\n${createProvenanceStamp('ng-add', '0.1.0')}`)).toBe(false);
    expect(hasProvenanceStamp('/* cngx:generated by hand */\n')).toBe(false);
  });
});

describe('withProvenanceMarker', () => {
  it('appends the marker before a trailing newline', () => {
    expect(withProvenanceMarker(IMPORT_LINE, 'theme-import')).toBe(
      "@import '@cngx/themes/cngx.css'; /* cngx:theme-import */\n",
    );
  });

  it('appends at the end when there is no trailing newline', () => {
    expect(withProvenanceMarker('provideA11yPreferences()', 'provider:a11y')).toBe(
      'provideA11yPreferences() /* cngx:provider:a11y */',
    );
  });

  it('rejects an id that could close the comment', () => {
    expect(() => withProvenanceMarker(IMPORT_LINE, 'x */ y')).toThrow('Invalid provenance marker id');
  });
});

describe('hasProvenanceMarker', () => {
  it('matches only the exact id', () => {
    const content = withProvenanceMarker(IMPORT_LINE, 'theme-import');

    expect(hasProvenanceMarker(content, 'theme-import')).toBe(true);
    expect(hasProvenanceMarker(content, 'theme')).toBe(false);
    expect(hasProvenanceMarker(IMPORT_LINE, 'theme-import')).toBe(false);
  });
});
