#!/usr/bin/env node
// Publish the compodocx llm-md export as llms.txt + llms-full.txt into the
// GH Pages artifact (docs/). Runs AFTER `npm run docs` and `npm run docs:llm`
// so the files land at the site root as plain static text - compodocx never
// sees them, so they cannot be picked up as additional pages.
//
//   llms-full.txt  - verbatim copy of .compodoc-llm/llm-context.md
//   llms.txt       - generated index: summary, packages, per-kind counts
//
// Base URL via DOCS_BASE_URL (defaults to the production GH Pages URL).

import { copyFile, readFile, readdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';

const DEFAULT_BASE_URL = 'https://cngxjs.github.io/cngx';

/** Count `### artifact` entries per `## kind` section of the llm-md dump. */
export function parseKindCounts(dump) {
  const counts = [];
  let current = null;
  for (const line of dump.split('\n')) {
    const kind = line.match(/^## (.+)$/);
    if (kind) {
      current = { kind: kind[1].trim(), count: 0 };
      counts.push(current);
      continue;
    }
    if (current && /^### /.test(line)) {
      current.count += 1;
    }
  }
  return counts.filter((entry) => entry.count > 0);
}

export function buildIndex({ baseUrl, packages, kindCounts, generatorLine }) {
  const total = kindCounts.reduce((sum, entry) => sum + entry.count, 0);
  const kinds = kindCounts.map((entry) => `${entry.count} ${entry.kind}`).join(', ');
  const lines = [
    '# cngx',
    '',
    '> Signal-native Angular component library: atoms, molecules and organisms',
    '> composed on plain Angular Signals and modern DOM. CDK and Material are',
    '> opt-in primitives, not foundations. A11y is part of the computed() graph.',
    '',
    `${total} documented exports (${kinds}).`,
    generatorLine ? `${generatorLine}` : null,
    '',
    '## API Reference',
    '',
    `- [Full API dump, llm-md format](${baseUrl}/llms-full.txt): every exported artifact with selector, inputs, outputs, description and live-example URLs`,
    `- [Documentation site](${baseUrl}/): rendered docs including core concepts and per-component theming tokens`,
    `- [Live examples](${baseUrl}/examples/): runnable demos, one route per example`,
    '',
    '## Packages',
    '',
    ...packages.map(
      (pkg) => `- [${pkg.name}](https://www.npmjs.com/package/${pkg.name}): ${pkg.description}`,
    ),
    '',
  ];
  return lines.filter((line) => line !== null).join('\n');
}

export async function readPackages(projectsDir) {
  const packages = [];
  for (const dir of await readdir(projectsDir)) {
    const manifestPath = resolve(projectsDir, dir, 'package.json');
    if (!existsSync(manifestPath)) {
      continue;
    }
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    if (manifest.private || !manifest.name?.startsWith('@cngx/')) {
      continue;
    }
    packages.push({ name: manifest.name, description: manifest.description ?? '' });
  }
  return packages.sort((a, b) => a.name.localeCompare(b.name));
}

async function main() {
  const cwd = process.cwd();
  const dumpPath = resolve(cwd, '.compodoc-llm/llm-context.md');
  const docsDir = resolve(cwd, 'docs');
  if (!existsSync(dumpPath)) {
    console.error(`llms-publish: missing ${dumpPath} - run \`npm run docs:llm\` first.`);
    process.exit(1);
  }
  if (!existsSync(docsDir)) {
    console.error(`llms-publish: missing ${docsDir} - run \`npm run docs\` first.`);
    process.exit(1);
  }

  const dump = await readFile(dumpPath, 'utf8');
  const generatorLine = dump
    .split('\n')
    .find((line) => line.startsWith('> Generated by'))
    ?.replace(/^> /, '');

  const index = buildIndex({
    baseUrl: (process.env.DOCS_BASE_URL ?? DEFAULT_BASE_URL).replace(/\/$/, ''),
    packages: await readPackages(resolve(cwd, 'projects')),
    kindCounts: parseKindCounts(dump),
    generatorLine,
  });

  await copyFile(dumpPath, resolve(docsDir, 'llms-full.txt'));
  await writeFile(resolve(docsDir, 'llms.txt'), index, 'utf8');
  console.log(
    `llms-publish: wrote docs/llms.txt (${index.length} bytes) and docs/llms-full.txt (${dump.length} bytes).`,
  );
}

const isDirectRun =
  process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isDirectRun) {
  await main();
}
