#!/usr/bin/env node
// Usage:
//   npm run schematics:tokens   # rewrite the generated module
//
// Distils the documented `@property` registrations of the cngx system tokens
// into the data the ng-add theme step writes as comments into a generated
// theme file: what each token controls, its default, the values it accepts
// (the registered syntax) and whether it inherits. The registrations are the
// single source; the schematic never carries a hand-written copy, and
// `scripts/__tests__/schematics-token-comments.test.mjs` fails when the
// generated module falls behind them.
//
// The source is the committed CSS, not `.compodoc/documentation.json`: the
// compodocx export attaches tokens to components and directives only, so the
// system tokens never reach it.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const SOURCE = 'projects/core/theming/system-tokens.css';
export const OUT = 'projects/core/schematics/ng-add/steps/theme-tokens.generated.ts';

// Source JSDoc may carry em/en dashes; the generated file lands in consumer
// apps, so they become a plain hyphen.
const DASHES = new RegExp(String.raw`\s*[\u2014\u2013]\s*`, 'g');
const normalizeDashes = (text) => text.replace(DASHES, ' - ');

function docText(block) {
  const lines = block
    .split('\n')
    .map((line) => line.replace(/^\s*\*\s?/, '').trim())
    .filter((line) => line !== '' && line !== '/' && !line.startsWith('/**'));
  const group = lines.find((line) => line.startsWith('@group '))?.slice('@group '.length).trim() ?? '';
  const description = normalizeDashes(lines.filter((line) => !line.startsWith('@')).join(' '));
  return { group, description };
}

function descriptor(body, name) {
  return new RegExp(String.raw`${name}\s*:\s*([^;]+);`).exec(body)?.[1].trim();
}

/** Every documented `@property` registration of `css`, in source order. */
export function collectBaseTokens(css) {
  const pattern = /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*@property\s+(--[\w-]+)\s*\{([^}]*)\}/g;
  return [...css.matchAll(pattern)].map((match) => {
    const { group, description } = docText(match[1]);
    const syntax = descriptor(match[3], 'syntax') ?? "'*'";
    return {
      name: match[2],
      group,
      description,
      syntax: syntax.replace(/^['"]|['"]$/g, ''),
      initialValue: descriptor(match[3], 'initial-value') ?? '',
      inherits: descriptor(match[3], 'inherits') === 'true',
    };
  });
}

export function sourceHash(css) {
  return `sha256:${createHash('sha256').update(css).digest('hex')}`;
}

const quote = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export function renderTokenModule(css) {
  const tokens = collectBaseTokens(css);
  const entries = tokens.map((token) =>
    [
      '  {',
      `    name: ${quote(token.name)},`,
      `    group: ${quote(token.group)},`,
      `    description: ${quote(token.description)},`,
      `    syntax: ${quote(token.syntax)},`,
      `    initialValue: ${quote(token.initialValue)},`,
      `    inherits: ${token.inherits},`,
      '  },',
    ].join('\n'),
  );
  return [
    `// Generated by scripts/schematics-token-comments.mjs from ${SOURCE}.`,
    '// Do not edit; run `npm run schematics:tokens`.',
    `// Source: ${sourceHash(css)}`,
    '',
    '/** A registered cngx system token, as its `@property` rule documents it. */',
    'export interface BaseToken {',
    '  readonly name: string;',
    '  readonly group: string;',
    '  readonly description: string;',
    '  /** The registered syntax: the values the token accepts. */',
    '  readonly syntax: string;',
    '  readonly initialValue: string;',
    '  readonly inherits: boolean;',
    '}',
    '',
    'export const BASE_TOKENS: readonly BaseToken[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

function main() {
  const css = readFileSync(resolve(ROOT, SOURCE), 'utf8');
  writeFileSync(resolve(ROOT, OUT), renderTokenModule(css));
  process.stdout.write(`${OUT}: ${collectBaseTokens(css).length} tokens\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
