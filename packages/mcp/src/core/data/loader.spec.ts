import { copyFileSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  createDocsIndex,
  loadBundledDocs,
  loadBundledLlmDump,
  loadDocsFromFile,
  loadLlmDumpFromFile,
  MalformedSnapshotError,
  SchemaVersionError,
  SnapshotLoadError,
  SUPPORTED_SCHEMA_VERSIONS,
} from './loader.js';
import { loadErrorCodesFromFile, parseErrorCodeBlock } from './loader.js';
import type { DocumentationJson } from './types.js';

const FIXTURE = fileURLToPath(new URL('../../../test/fixtures/documentation.sample.json', import.meta.url));
const V6_FIXTURE = fileURLToPath(new URL('../../../test/fixtures/documentation.v6.sample.json', import.meta.url));
const LLM_DUMP_FIXTURE = fileURLToPath(new URL('../../../test/fixtures/llm-context.sample.md', import.meta.url));

function readFixture(): DocumentationJson {
  return JSON.parse(readFileSync(FIXTURE, 'utf8')) as DocumentationJson;
}

describe('loadDocsFromFile', () => {
  it('loads the fixture into a typed index with provenance meta', () => {
    const index = loadDocsFromFile(FIXTURE);

    expect(index.meta.schemaVersion).toBe(2);
    expect(index.meta.cngxVersion).toBe('0.1.0-rc.6');
    expect(index.meta.generatedAt).toBe('2026-08-17T11:21:23.588Z');
    expect(index.components.length).toBeGreaterThan(0);
    expect(index.directives.length).toBeGreaterThan(0);
    expect(index.injectables.length).toBeGreaterThan(0);
    expect(index.tokens.length).toBeGreaterThan(0);
  });

  it('defaults injectables to an empty array for a snapshot that predates them', () => {
    const raw = readFixture();
    delete raw.injectables;

    expect(createDocsIndex(raw).injectables).toEqual([]);
  });
});

describe('loadLlmDumpFromFile', () => {
  it('returns the verbatim dump text for a present file', () => {
    const dump = loadLlmDumpFromFile(LLM_DUMP_FIXTURE);

    expect(dump).toBe(readFileSync(LLM_DUMP_FIXTURE, 'utf8'));
    expect(dump).toContain('> Generated by compodocx');
  });

  it('returns null for a missing path', () => {
    expect(loadLlmDumpFromFile(FIXTURE.replace('documentation.sample.json', 'nope.md'))).toBeNull();
  });
});

describe('bundled loaders', () => {
  it('read documentation.json and llm-context.md from the data directory the caller passes', () => {
    const dataDir = mkdtempSync(join(tmpdir(), 'cngx-mcp-data-'));
    copyFileSync(FIXTURE, join(dataDir, 'documentation.json'));

    expect(loadBundledDocs(dataDir).meta.cngxVersion).toBe('0.1.0-rc.6');
    expect(loadBundledLlmDump(dataDir)).toBeNull();

    copyFileSync(LLM_DUMP_FIXTURE, join(dataDir, 'llm-context.md'));
    expect(loadBundledLlmDump(dataDir)).toBe(readFileSync(LLM_DUMP_FIXTURE, 'utf8'));
  });
});

describe('createDocsIndex schema guard', () => {
  it('supports schema 2, 6 and 7', () => {
    expect(SUPPORTED_SCHEMA_VERSIONS).toEqual([2, 6, 7]);
  });

  it('accepts a schema-2 snapshot', () => {
    expect(() => createDocsIndex(readFixture())).not.toThrow();
  });

  it('accepts a schema-6 snapshot and projects category and factoryKind', () => {
    const index = loadDocsFromFile(V6_FIXTURE);

    expect(index.meta).toMatchObject({ schemaVersion: 6, cngxVersion: '0.1.0-rc.9' });
    expect(index.components.find((entry) => entry.name === 'CngxSelect')?.category).toBe('forms/select');
    expect(index.functions.find((fn) => fn.name === 'provideSelectConfig')?.factoryKind).toBe('provider');
  });

  it('accepts a schema-7 snapshot and projects it like schema 6', () => {
    const v6 = JSON.parse(readFileSync(V6_FIXTURE, 'utf8')) as DocumentationJson;
    const index = createDocsIndex({ ...v6, schemaVersion: 7 });

    expect(index.meta).toMatchObject({ schemaVersion: 7, cngxVersion: '0.1.0-rc.9' });
    expect(index.components.find((entry) => entry.name === 'CngxSelect')?.category).toBe('forms/select');
    expect(index.functions.find((fn) => fn.name === 'provideSelectConfig')?.factoryKind).toBe('provider');
  });

  it('rejects a snapshot whose schemaVersion the server does not support, naming every supported version', () => {
    const mismatched: DocumentationJson = { ...readFixture(), schemaVersion: 3 };

    expect(() => createDocsIndex(mismatched)).toThrow(SchemaVersionError);
    expect(() => createDocsIndex(mismatched)).toThrow(MalformedSnapshotError);
    expect(() => createDocsIndex(mismatched)).toThrow(/schemaVersion 3; this package reads 2, 6 and 7/);
  });

  it('normalises a missing cngxVersion to null', () => {
    const raw = readFixture();
    delete raw.cngxVersion;

    expect(createDocsIndex(raw).meta.cngxVersion).toBeNull();
  });
});

describe('createDocsIndex functions projection', () => {
  it('projects miscellaneous.functions into docs.functions', () => {
    const raw: DocumentationJson = {
      ...readFixture(),
      miscellaneous: {
        functions: [
          { name: 'provideSelectConfig', file: 'projects/forms/select/shared/config.ts', factoryKind: 'provider' },
          {
            name: 'withPanelWidth',
            file: 'projects/forms/select/shared/config.ts',
            factoryKind: 'feature',
            returnType: 'CngxSelectConfigFeature',
          },
        ],
      },
    };

    const index = createDocsIndex(raw);

    expect(index.functions).toHaveLength(2);
    expect(index.functions.map((fn) => fn.name)).toEqual(['provideSelectConfig', 'withPanelWidth']);
    expect(index.functions[1].returnType).toBe('CngxSelectConfigFeature');
  });

  it('defaults docs.functions to an empty array when miscellaneous is absent', () => {
    const raw = readFixture();
    delete raw.miscellaneous;

    expect(createDocsIndex(raw).functions).toEqual([]);
  });
});

describe('createDocsIndex error-code projection', () => {
  const validBlock = () => ({
    schemaVersion: 3,
    docsBaseUrl: 'https://cngxjs.github.io/cngx/main/additional-documentation/error-codes/',
    ranges: [{ lib: 'core', from: 1, to: 899 }],
    codes: [
      {
        code: 'CNGX0001',
        lib: 'core',
        severity: 'warn',
        production: 'stripped',
        title: 'Locale is not a BCP 47 tag',
        status: 'active',
        url: 'https://cngxjs.github.io/cngx/main/additional-documentation/error-codes/cngx0001.html',
        messages: ['formatMessage(): not a BCP 47 locale'],
        body: '## Locale is not a BCP 47 tag',
      },
    ],
  });

  it('projects a valid block onto errorCodes, without its manifest schemaVersion', () => {
    const block = validBlock();
    const index = createDocsIndex({ ...readFixture(), cngxErrorCodes: block } as DocumentationJson);

    expect(index.errorCodes).toEqual({ docsBaseUrl: block.docsBaseUrl, ranges: block.ranges, codes: block.codes });
  });

  it('gives errorCodes null for an absent block', () => {
    expect(createDocsIndex(readFixture()).errorCodes).toBeNull();
  });

  it('gives errorCodes null for another manifest schemaVersion, and still loads components', () => {
    const raw = { ...readFixture(), cngxErrorCodes: { ...validBlock(), schemaVersion: 4 } } as DocumentationJson;
    const index = createDocsIndex(raw);

    expect(index.errorCodes).toBeNull();
    expect(index.components.length).toBeGreaterThan(0);
  });

  it('gives errorCodes null for a non-list codes', () => {
    const raw = { ...readFixture(), cngxErrorCodes: { ...validBlock(), codes: 'nope' } } as unknown as DocumentationJson;

    expect(createDocsIndex(raw).errorCodes).toBeNull();
  });
});

describe('a malformed snapshot', () => {
  const v6 = (patch: Record<string, unknown>) => ({ schemaVersion: 6, ...patch }) as unknown as DocumentationJson;
  const v2 = (patch: Record<string, unknown>) => ({ schemaVersion: 2, ...patch }) as unknown as DocumentationJson;

  it.each([
    ['a null document', null as unknown as DocumentationJson],
    ['a non-array component list', v6({ components: { name: 'CngxX' } })],
    ['a non-array token list', v6({ tokens: 'CNGX_X' })],
    ['a non-array function list', v6({ miscellaneous: { functions: 42 } })],
    ['a schema-6 feature without an entry point', v6({ components: [{ name: 'CngxX', feature: {} }] })],
    ['a schema-2 input default that is not text', v2({ components: [{ name: 'CngxX', inputsClass: [{ name: 'x', defaultValue: 7 }] }] })],
  ])('throws MalformedSnapshotError for %s', (_, raw) => {
    expect(() => createDocsIndex(raw)).toThrow(MalformedSnapshotError);
  });

  it('names neither the mcp package nor a regeneration step, and points at the install', () => {
    const errors = [
      () => createDocsIndex(v6({ components: { name: 'CngxX' } })),
      () => createDocsIndex({ ...readFixture(), schemaVersion: 3 }),
    ];
    for (const load of errors) {
      let message = '';
      try {
        load();
      } catch (error) {
        message = (error as Error).message;
      }

      expect(message).not.toContain('@cngx/mcp');
      expect(message).not.toMatch(/regenerate/i);
      expect(message).toContain('reinstall the package that bundles this snapshot');
    }
  });

  it('gives a missing bundled snapshot the reinstall hint instead of a bare ENOENT', () => {
    const dir = mkdtempSync(join(tmpdir(), 'cngx-loader-'));

    expect(() => loadBundledDocs(dir)).toThrow(SnapshotLoadError);
    expect(() => loadBundledDocs(dir)).toThrow(
      'documentation.json cannot be read (ENOENT); reinstall the package that bundles this snapshot.',
    );
  });

  it('makes every snapshot error a SnapshotLoadError', () => {
    expect(new SchemaVersionError(3)).toBeInstanceOf(SnapshotLoadError);
    expect(new MalformedSnapshotError('x')).toBeInstanceOf(SnapshotLoadError);
  });

  it('throws MalformedSnapshotError for a file that is not JSON', () => {
    const dir = mkdtempSync(join(tmpdir(), 'cngx-loader-'));
    const path = join(dir, 'documentation.json');
    writeFileSync(path, '{ "schemaVersion": 6,');

    expect(() => loadDocsFromFile(path)).toThrow(MalformedSnapshotError);
  });
});

describe('loadErrorCodesFromFile', () => {
  const block = {
    schemaVersion: 3,
    docsBaseUrl: 'https://example.test/',
    ranges: [{ lib: 'core', from: 1, to: 899 }],
    codes: [],
  };

  function assetFile(body: string): string {
    const path = join(mkdtempSync(join(tmpdir(), 'cngx-error-codes-')), 'error-codes.json');
    writeFileSync(path, body);
    return path;
  }

  it('reads a valid block onto the index, without its manifest schemaVersion', () => {
    expect(loadErrorCodesFromFile(assetFile(JSON.stringify(block)))).toEqual({
      docsBaseUrl: block.docsBaseUrl,
      ranges: block.ranges,
      codes: block.codes,
    });
  });

  it('throws naming the schemaVersion it reads for another manifest schema', () => {
    const path = assetFile(JSON.stringify({ ...block, schemaVersion: 4 }));

    expect(() => loadErrorCodesFromFile(path)).toThrow(SnapshotLoadError);
    expect(() => loadErrorCodesFromFile(path)).toThrow(/this package reads manifest schemaVersion 3/);
  });

  it('throws for a file that is not JSON', () => {
    expect(() => loadErrorCodesFromFile(assetFile('{ "schemaVersion":'))).toThrow(SnapshotLoadError);
  });

  it('throws for a missing file', () => {
    expect(() => loadErrorCodesFromFile(join(tmpdir(), 'cngx-no-such-dir', 'error-codes.json'))).toThrow(SnapshotLoadError);
  });

  it('reads the same rules as the block inside a snapshot', () => {
    expect(parseErrorCodeBlock(undefined)).toBeNull();
    expect(parseErrorCodeBlock({ ...block, codes: 'nope' })).toBeNull();
  });
});
